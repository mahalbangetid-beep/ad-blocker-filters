const SVG_NS = 'http://www.w3.org/2000/svg';

export function ic(name, cls = '') {
  return `<svg class="ic ${cls}" viewBox="0 0 24 24" aria-hidden="true">${ICONS[name] || ''}</svg>`;
}

function parse(markup) {
  const t = document.createElement('template');
  t.innerHTML = markup;
  return t.content.firstElementChild;
}

export function icon(name, cls = '') {
  return parse(ic(name, cls));
}

// Core gradient lives inside each logo; ids are unique per instance so several logos can coexist.
let logoSeq = 0;
function logoMarkup(cls) {
  const id = `lg-core-${++logoSeq}`;
  return `<svg class="logo ${cls}" viewBox="0 0 40 40" aria-hidden="true"><defs><radialGradient id="${id}" cx="38%" cy="34%" r="70%"><stop offset="0" stop-color="#FFF6E0"/><stop offset=".45" stop-color="#FFB547"/><stop offset="1" stop-color="#FF7A8A"/></radialGradient></defs><g class="core"><circle cx="20" cy="20" r="7.5" fill="url(#${id})"/></g><g class="orb"><ellipse cx="20" cy="20" rx="17" ry="6.5" fill="none" style="stroke:var(--logo-ring)" stroke-width="1.3" transform="rotate(-24 20 20)"/><circle cx="35.2" cy="13.4" r="2.6" fill="#5EEAD4"/></g></svg>`;
}

export function logo(cls = '') {
  return parse(logoMarkup(cls));
}

// Replace <i data-ic="name"> with icons and fill <svg data-logo> with the logo.
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('i[data-ic]')) el.replaceWith(icon(el.dataset.ic, el.className));
  for (const el of root.querySelectorAll('svg[data-logo]')) {
    const l = logo(el.getAttribute('class') || '');
    el.replaceWith(l);
  }
}
